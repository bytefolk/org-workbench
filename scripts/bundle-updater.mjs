import crypto from "node:crypto";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import esbuild from "esbuild";

const require = createRequire(import.meta.url);

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Every package whose code ends up inside the bundle. Walked from the manifest
 * rather than listed, so a dependency bump cannot silently drop a notice.
 */
export function bundledPackages(root, entry = "electron-updater") {
  const seen = new Set();
  const visit = (name) => {
    if (seen.has(name)) return;
    seen.add(name);
    let manifest;
    try {
      manifest = require(path.join(root, "node_modules", name, "package.json"));
    } catch {
      return;
    }
    for (const dependency of Object.keys(manifest.dependencies ?? {})) visit(dependency);
  };
  visit(entry);
  return [...seen].sort();
}

/**
 * Collect the notices the bundled licences require to travel with the code.
 *
 * MIT and ISC both say the copyright and permission notice must appear in all
 * copies or substantial portions; Python-2.0 requires retention too. Bundling
 * turns 16 packages into one file, so without this that file is a copy carrying
 * none of them. esbuild's `legalComments` does not cover it: it preserves
 * comments found in source, and these packages keep their licence text in
 * separate LICENSE files it never reads.
 */
export function collectNotices(root, packages) {
  const sections = [];
  const missing = [];
  for (const name of packages) {
    const directory = path.join(root, "node_modules", name);
    let manifest;
    try {
      manifest = require(path.join(directory, "package.json"));
    } catch {
      missing.push(name);
      continue;
    }
    const file = fs.readdirSync(directory).find((entry) => /^(LICENSE|LICENCE|COPYING)/i.test(entry));
    const declared = manifest.license ?? "UNKNOWN";
    if (file === undefined) {
      // No licence file to quote. The declaration is still recorded rather than
      // dropped, and the omission is visible instead of silent.
      missing.push(`${name} (${declared})`);
      sections.push(`${name}@${manifest.version} — ${declared}\n(no licence file published with this package)`);
      continue;
    }
    const text = fs.readFileSync(path.join(directory, file), "utf8").trim();
    sections.push(`${name}@${manifest.version} — ${declared}\n\n${text}`);
  }
  return { sections, missing };
}

export const VENDOR_RELATIVE = "apps/desktop/src/vendor/electron-updater.cjs";

/**
 * electron-updater is the app's only third-party runtime dependency, and the
 * staging manifest is a per-file allowlist with no third-party node_modules set
 * -- deliberately, because the packaged tree is a boundary. Shipping the package
 * as-is would add 16 packages and 325 files to a tree that asserts 189 files
 * byte-exact.
 *
 * So it is bundled to a single vendored file, which the manifest names as one
 * entry. The reference project takes the same approach for the same reason: it
 * bundles its whole main process and lists only `node-pty` from node_modules,
 * because a native module cannot be bundled. electron-updater is pure JS, so it
 * can be.
 *
 * The main process itself stays as source. Bundling one dependency is a smaller
 * change than changing how the shell ships.
 */
export async function bundleUpdater({ root = projectRoot, write = true } = {}) {
  const outfile = path.join(root, VENDOR_RELATIVE);
  const packages = bundledPackages(root);
  const { sections } = collectNotices(root, packages);
  const banner = [
    "/*",
    " * Bundled third-party code. Generated by scripts/bundle-updater.mjs; do not edit.",
    " *",
    " * The licences below travel with this file because the code they cover is in it.",
    " * MIT and ISC require their notice in all copies or substantial portions of the",
    " * software, and bundling makes this file such a copy.",
    " */",
    ...sections.map((section) => `/*\n${section.split("\n").map((line) => ` * ${line}`.trimEnd()).join("\n")}\n */`),
  ].join("\n");

  const result = await esbuild.build({
    banner: { js: banner },
    entryPoints: [path.join(root, "node_modules", "electron-updater", "out", "main.js")],
    outfile,
    bundle: true,
    platform: "node",
    format: "cjs",
    // Electron 43 ships Node 22. Targeting lower would only cost transpilation
    // this runtime does not need.
    target: "node20",
    // `electron` is provided by the runtime, never bundled.
    external: ["electron"],
    // Keep it legible enough to read a stack trace in a packaged app.
    minify: false,
    sourcemap: false,
    legalComments: "inline",
    logLevel: "silent",
    write,
    ...(write ? {} : { write: false }),
  });
  if (!write) {
    return { bytes: result.outputFiles[0].contents, sha256: null };
  }
  const contents = fs.readFileSync(outfile);
  return {
    outfile,
    relative: VENDOR_RELATIVE,
    packages: packages.length,
    notices: sections.length,
    bytes: contents.length,
    sha256: crypto.createHash("sha256").update(contents).digest("hex"),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  bundleUpdater()
    .then((report) => console.log(JSON.stringify({ schemaVersion: "org-workbench-vendor-bundle.v1", ...report })))
    .catch((error) => {
      console.error(error instanceof Error ? error.message : String(error));
      process.exit(1);
    });
}
